#!/usr/bin/env bash
#
# Builds two interposing libraries for the iOS Simulator in build/gl-trap/.
# Inserted with DYLD_INSERT_LIBRARIES, they replace OpenGL ES functions with
# one that prints the function and its caller and ends the process with exit
# code 86, the way a call would fail if OpenGLES.framework were missing.
#
#   libgltrap.dylib            every OpenGL ES function the PPSSPP core imports.
#                              A Vulkan or software run that survives it made
#                              no OpenGL ES call.
#   libgltrap-core-only.dylib  the same minus the functions the spike app
#                              imports itself. On the OpenGL ES path it must
#                              stop at the core's first call, which shows that
#                              the trap reaches the core.
#
# Usage: make-gl-trap.sh   (after Scripts/build-core.sh ppsspp and the app build)
# Run:   SIMCTL_CHILD_DYLD_INSERT_LIBRARIES="$PWD/build/gl-trap/libgltrap.dylib" \
#          Spikes/PSPGPU/Scripts/run-spike.sh <udid> vulkan <output dir>

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
core="$repo_root/Cores/Build/ppsspp_libretro.xcframework/ios-arm64-simulator/ppsspp_libretro.framework/ppsspp_libretro"
app="$repo_root/build/DerivedData-pspgpu/Build/Products/Debug-iphonesimulator/PSPGPUSpike.app"
out="$repo_root/build/gl-trap"

for required in "$core" "$app"; do
  if [[ ! -e "$required" ]]; then
    echo "error: $required is missing, build the core and the app first" >&2
    exit 66
  fi
done

# Prints the OpenGL ES functions a Mach-O file imports, without the leading _.
gl_imports() {
  xcrun dyld_info -imports "$1" | awk '/\(from OpenGLES\)/ { sub(/^_/, "", $2); print $2 }' | sort -u
}

core_symbols="$(gl_imports "$core")"
if [[ -z "$core_symbols" ]]; then
  echo "error: the core imports nothing from OpenGLES" >&2
  exit 65
fi
app_symbols="$(
  for binary in "$app/PSPGPUSpike" "$app"/*.dylib; do
    [[ -f "$binary" ]] && gl_imports "$binary"
  done | sort -u
)"

# Writes a C file with one interposed replacement per symbol on stdin.
write_source() {
  cat << 'C'
// Generated by Spikes/PSPGPU/Scripts/make-gl-trap.sh, do not edit.
#include <dlfcn.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

struct interpose {
    const void *replacement;
    const void *original;
};

static void trap(const char *name, const void *caller) {
    Dl_info info = {0};
    dladdr(caller, &info);
    const char *image = info.dli_fname ? info.dli_fname : "?";
    const char *inApp = strstr(image, ".app/");
    fprintf(stderr, "GL TRAP: %s called from %s%s\n", name, inApp ? "<app>" : "", inApp ? inApp + 4 : image);
    _exit(86);
}

// The section type "interposing" (S_INTERPOSING) is what dyld looks for, the
// same declaration as DYLD_INTERPOSE in dyld's own dyld-interposing.h.
#define TRAP(symbol)                                                                       \
    extern void symbol(void);                                                              \
    static void trap_##symbol(void) { trap(#symbol, __builtin_return_address(0)); }        \
    __attribute__((used, section("__DATA,__interpose,interposing"))) static struct interpose \
        interpose_##symbol = {(const void *)trap_##symbol, (const void *)symbol};

C
  sed 's/.*/TRAP(&)/'
}

build() {
  local name="$1" symbols="$2"
  write_source <<< "$symbols" > "$out/$name.c"
  xcrun --sdk iphonesimulator clang -target arm64-apple-ios27.0-simulator -dynamiclib -O1 \
    -Wall -Wextra -Werror -framework OpenGLES -o "$out/$name.dylib" "$out/$name.c"
  codesign --force --sign - --timestamp=none "$out/$name.dylib" 2> /dev/null
  echo "Wrote build/gl-trap/$name.dylib with $(wc -l <<< "$symbols" | tr -d ' ') traps"
}

mkdir -p "$out"
build libgltrap "$core_symbols"
build libgltrap-core-only "$(comm -23 <(echo "$core_symbols") <(echo "$app_symbols"))"
